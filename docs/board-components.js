const DEFAULT_OPTIONS = { tilt: false, expander: false };

export function getVisibleComponents(options = {}) {
  const o = { ...DEFAULT_OPTIONS, ...options };
  return COMPONENTS.filter((c) => !c.optional || o[c.optionKey]);
}

export function resolveSelection(id, options = {}) {
  const visible = new Set(getVisibleComponents(options).map((c) => c.id));
  return visible.has(id) ? id : 'cam';
}
